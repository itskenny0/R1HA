package com.github.itskenny0.r1ha.core.lovelace

import androidx.compose.runtime.Immutable
import kotlinx.serialization.json.JsonObject

/**
 * Typed in-memory model for a parsed HA Lovelace dashboard configuration.
 *
 * Mirrors the subset of `lovelace/config` shape that the dashboards renderer
 * understands today. Any card type we don't model is preserved as
 * [LovelaceCard.Unsupported] with its raw JSON payload intact, so the screen
 * can still show a placeholder + the original config for debugging without
 * dropping it from the view.
 *
 * Read-only on R1HA's side: parsing happens once per dashboard fetch and the
 * tree is treated as immutable. Local-only edits land as a separate overrides
 * layer (see [LovelaceOverrides]) keyed by `(viewPath, cardIndex)`, applied at
 * render time so the imported HA config is never mutated.
 *
 * @Immutable so Compose can skip recomposition when references haven't changed.
 */
@Immutable
data class LovelaceConfig(
    val title: String?,
    val views: List<LovelaceView>,
    /**
     * `true` when the dashboard is entirely generated by an HA *strategy*
     * (the `strategy:` key at the config root, with no concrete `views`).
     * HA's default auto-dashboard is the canonical example: the server only
     * returns `{ "strategy": { "type": "original-states" } }` and expects the
     * frontend to expand it client-side, which R1HA can't do natively. The
     * screen reads this flag to show an "open in Lovelace" affordance instead
     * of silently rendering an empty dashboard.
     */
    val isStrategyGenerated: Boolean = false,
    /**
     * Dashboard-level `background:` (`config.background`). HA falls back to this
     * when a view declares no `background:` of its own (hui-root.ts:
     * `curViewConfig?.background || config.background`). Null when the dashboard
     * sets none; see [resolveViewBackground].
     */
    val background: LovelaceViewBackground? = null,
)

/** One view inside a dashboard. corresponds to a tab in HA's frontend. */
@Immutable
data class LovelaceView(
    /** User-facing title; falls back to the path or index when empty. */
    val title: String?,
    /**
     * URL-style identifier HA uses to address the view (e.g. "lights",
     * "default_view"). Stable across HA restarts; we key local overrides
     * against it so reordering views in HA doesn't shuffle our overrides.
     * Falls back to the index-as-string when the YAML omits it.
     */
    val path: String,
    /** Optional MDI icon string (`mdi:lightbulb` etc.). */
    val icon: String?,
    /**
     * `true` when the view should render its cards in panel mode (single
     * card filling the viewport). We honour this when rendering: a `panel: true`
     * view with one card hides the surrounding scroll/padding chrome.
     */
    val panel: Boolean,
    /**
     * The parsed cards in display order. Empty when the view exists but
     * has no cards (legitimate during early-edit on HA's side).
     */
    val cards: List<LovelaceCard>,
    /**
     * The view's top-level `badges:` array (HA renders these as a row of
     * chips above the cards). Empty when the view declares none. Each badge
     * is an entity-state chip with an optional tap action; see [LovelaceBadge].
     */
    val badges: List<LovelaceBadge> = emptyList(),
    /**
     * `true` when this view delegates its layout to an HA *strategy* (a
     * `strategy:` key on the view, or on every one of its sections) and so
     * carries no concrete cards we can render. The screen surfaces the
     * "open in Lovelace" affordance for such a view rather than an empty
     * scroll. A view that mixes a strategy section with concrete sections
     * keeps the concrete cards and is NOT flagged.
     */
    val isStrategyGenerated: Boolean = false,
    /**
     * `true` when this is a sub-view (HA 2022.10). Sub-views are navigated
     * to via `navigate` actions rather than shown as top-level tabs, so they
     * are filtered out of the dashboard's view list. They remain fully
     * renderable when navigated directly.
     */
    val subview: Boolean = false,
    /**
     * HA view `header:` (HA 2025.x): an optional card rendered above the
     * badges/cards (typically a markdown title), plus the layout + badge
     * placement options. Null when the view declares no header. R1HA renders
     * the header card and threads [LovelaceViewHeader.badgesPosition] /
     * [LovelaceViewHeader.layout] into the single-column flow; see
     * [LovelaceViewHeader] and [resolveHeaderPlan].
     */
    val header: LovelaceViewHeader? = null,
    /**
     * HA view `footer:` : an optional card rendered after the last card. Null
     * when the view declares none. On the 640px R1 column the footer renders
     * inline at the bottom of the scroll (HA's sticky/max_width chrome is a
     * wide-desktop affordance and is documented as a no-op here; see
     * [LovelaceViewFooter]).
     */
    val footer: LovelaceViewFooter? = null,
    /**
     * HA sections-view `sidebar:` : a distinct group of sections HA renders in
     * a side rail. On the single 640px column R1HA flattens these after the
     * main sections under a divider, honouring the sidebar's own visibility
     * conditions; see [LovelaceViewSidebar] and [resolveSidebarVisible].
     */
    val sidebar: LovelaceViewSidebar? = null,
    /**
     * HA view `background:` ({image, opacity, size, alignment, repeat,
     * attachment} or a bare string). Rendered behind the cards via HuiImage.
     * Null when the view declares none; the dashboard-level background is then
     * the fallback (see [LovelaceConfig.background] and [resolveViewBackground]).
     */
    val background: LovelaceViewBackground? = null,
    /**
     * HA view `visible:` : `false` hides the view from the tab/page list, an
     * array of `{user: id}` shows it only to listed users. Null = always
     * visible. The view stays navigable by direct path even when hidden, so
     * this only gates the tab list (see [ViewVisibility] and [isViewTabVisible]).
     */
    val visible: ViewVisibility? = null,
    /**
     * HA subview `back_path:` : when this is a subview, back navigation goes to
     * the configured view path instead of the previous screen. Null = the
     * normal back stack. Only meaningful when [subview] is true.
     */
    val backPath: String? = null,
    /**
     * HA `show_icon_and_title:` : when true (and both an [icon] and [title]
     * exist) the tab/page indicator shows the icon AND the title rather than
     * collapsing to one. False/null = HA's default (icon alone when present,
     * else title). See [resolveTabIndicator].
     */
    val showIconAndTitle: Boolean = false,
    /**
     * HA sections-view `max_columns:` (default 4). On the single-column R1
     * flatten this affects card ORDER only, never multi-column layout; stored
     * so the ordering pass and a `view_columns` condition can read it. Null =
     * HA's default.
     */
    val maxColumns: Int? = null,
    /**
     * HA sections-view `dense_section_placement:` : when true HA packs section
     * tiles densely (CSS grid auto-flow dense). On the single-column flatten
     * this never changes layout; stored so the order pass documents the
     * adaptation. Defaults false.
     */
    val denseSectionPlacement: Boolean = false,
    /**
     * HA sections-view `top_margin:` : when true HA adds extra space above the
     * first section. Honoured as a small leading spacer in the flatten.
     * Defaults false.
     */
    val topMargin: Boolean = false,
    /**
     * The view's parsed sections in declaration order (a sections-view only).
     * Empty for a masonry/panel view. Each [LovelaceSection] carries its span
     * keys, disabled flag, and background; the renderer flattens them into the
     * single column in HA's reading order (see [orderedSectionCards]). The
     * flat [cards] list above remains the authoritative render input; [sections]
     * is the structural detail the ordering + section-background passes read.
     */
    val sections: List<LovelaceSection> = emptyList(),
    /**
     * Per-view `theme:` key. Stored only; theme application is the theming
     * batch's job. Null = inherit the dashboard/global theme.
     */
    val theme: String? = null,
)

/**
 * HA view `header:` config (`LovelaceViewHeaderConfig`). The header is a small
 * subsystem rendered above the view's cards.
 *
 *  - [card]: any card (HA's editor defaults to a text-only markdown title);
 *    null when the header carries only badges.
 *  - [layout]: "start" / "center" / "responsive". On the single 640px column
 *    "responsive" collapses to "start" (there is never room to float badges
 *    beside the heading); see [resolveHeaderPlan].
 *  - [badgesPosition]: "top" (badges above the header card) or "bottom"
 *    (default, badges below the header card).
 *  - [badgesWrap]: "wrap" (default) or "scroll". The R1 badge row already
 *    scrolls horizontally, so "wrap" is the only meaningful adaptation on the
 *    narrow panel; the key is stored and documented.
 */
@Immutable
data class LovelaceViewHeader(
    val card: LovelaceCard?,
    val layout: String? = null,
    val badgesPosition: String? = null,
    val badgesWrap: String? = null,
)

/**
 * HA view `footer:` config (`LovelaceViewFooterConfig`).
 *
 *  - [card]: the card rendered after the last view card. Null when absent.
 *  - [maxWidth]: HA's `max_width` (default 600px) caps the footer width on a
 *    wide desktop. On the 640px R1 column this never bites, so it is stored and
 *    documented but does not constrain layout.
 *
 * HA pins the footer sticky to the bottom of the viewport on desktop. R1HA's
 * single scroll column renders it inline at the end (non-sticky); this is a
 * deliberate small-screen adaptation, not a dropped key.
 */
@Immutable
data class LovelaceViewFooter(
    val card: LovelaceCard?,
    val maxWidth: Int? = null,
)

/**
 * HA sections-view `sidebar:` config (`LovelaceViewSidebarConfig`). HA renders
 * the sidebar's sections in a side rail beside the main grid; on the single
 * 640px column R1HA flattens them after the main sections under a divider.
 *
 *  - [sections]: the sidebar's own sections (flattened the same way the main
 *    sections are).
 *  - [contentLabel] / [sidebarLabel]: the labels HA's mobile tab switcher uses
 *    for the main content vs the sidebar. R1HA uses [sidebarLabel] as the
 *    divider caption above the flattened sidebar group (falling back to a
 *    generic "More" when blank).
 *  - [visibility]: conditions gating the whole sidebar group (HA hides the
 *    sidebar when they fail). Evaluated through the Batch B engine; see
 *    [resolveSidebarVisible].
 */
@Immutable
data class LovelaceViewSidebar(
    val sections: List<LovelaceSection> = emptyList(),
    val contentLabel: String? = null,
    val sidebarLabel: String? = null,
    val visibility: List<LovelaceCondition> = emptyList(),
)

/**
 * One section of a sections-view (`LovelaceSectionConfig`). R1HA flattens every
 * section's cards into the view's single column; the structural keys here drive
 * the flatten ORDER and the per-section background, never a real multi-column
 * layout (the 640px portrait panel has room for exactly one column, so the
 * flatten IS the equivalent of HA's grid here).
 *
 *  - [cards]: the section's cards, already parsed (a section header/footer card
 *    is folded into this list by the parser, matching the flat [LovelaceView.cards]).
 *  - [disabled]: HA's `disabled: true` drops the whole section from the render.
 *  - [columnSpan] / [rowSpan]: HA grid spans. Used only to compute reading
 *    order on the flatten (see [orderedSectionCards]); they never widen a card.
 *  - [background]: HA's `background` (true, or {color, opacity}). Resolved by
 *    [resolveSectionBackgroundOpacity]. Because the view flattens every section
 *    into one card column (so section boundaries are not preserved in the flat
 *    [LovelaceView.cards] render list), the per-section surface is parsed +
 *    resolved here but drawn by the renderer only when it iterates [sections]
 *    directly; the flat-list render path leaves it on the plain surface.
 *  - [topMargin]: HA's section `top_margin`, honoured as leading spacing.
 *  - [theme]: per-section theme key, stored for the theming batch.
 */
@Immutable
data class LovelaceSection(
    val cards: List<LovelaceCard>,
    val disabled: Boolean = false,
    val columnSpan: Int? = null,
    val rowSpan: Int? = null,
    val background: LovelaceSectionBackground? = null,
    val topMargin: Boolean = false,
    val theme: String? = null,
)

/**
 * HA section `background:` config (`LovelaceSectionBackgroundConfig`), or the
 * bare `background: true` shorthand (resolves to a default-opacity surface).
 *
 *  - [color]: a theme colour name or `#rrggbb`. Null = the default surface.
 *  - [opacity]: 0..100 percent (HA's `DEFAULT_SECTION_BACKGROUND_OPACITY` is
 *    50). Null = the default.
 */
@Immutable
data class LovelaceSectionBackground(
    val color: String? = null,
    val opacity: Int? = null,
)

/**
 * HA view `background:` config (`LovelaceViewBackgroundConfig`), or the bare
 * `background: <css/url string>` shorthand. R1HA renders the image (when one
 * resolves) behind the view's cards via HuiImage.
 *
 *  - [image]: a static image URL, or a `media-source://` content id (resolved
 *    by the image layer where supported; an unresolvable id shows nothing and
 *    the cards render on the plain surface).
 *  - [opacity]: 0..100 percent dimming applied to the image. Null = opaque.
 *  - [size]: "auto" / "cover" / "contain" (HA default "cover").
 *  - [alignment]: HA's nine-point alignment string (default "center").
 *  - [repeat]: "repeat" / "no-repeat" (HA default "no-repeat").
 *  - [attachment]: "scroll" / "fixed". R1HA renders the background fixed behind
 *    the scrolling column regardless; the key is stored and documented.
 *  - [rawString]: the original bare-string form when the config was a plain
 *    string rather than an object (HA accepts both). Preserved so a theme-token
 *    or gradient string is not silently dropped; the renderer uses [image] when
 *    it parses to a URL and otherwise falls back to the plain surface.
 */
@Immutable
data class LovelaceViewBackground(
    val image: String? = null,
    val opacity: Int? = null,
    val size: String? = null,
    val alignment: String? = null,
    val repeat: String? = null,
    val attachment: String? = null,
    val rawString: String? = null,
)

/**
 * HA view `visible:` config. HA accepts:
 *  - `visible: false` -> [AlwaysHidden]: the view is dropped from the tab list
 *    for everyone (but stays navigable by direct path).
 *  - `visible: [{user: id}, ...]` -> [Users]: the view appears in the tab list
 *    only for the listed user ids.
 *  - `visible: true` / omitted -> no [ViewVisibility] at all (always visible).
 *
 * Modelled as a sealed type so the tab filter ([isViewTabVisible]) reads a
 * single value instead of juggling a nullable boolean and a list.
 */
@Immutable
sealed interface ViewVisibility {
    /** `visible: false` — never shown in the tab list. */
    @Immutable
    data object AlwaysHidden : ViewVisibility
    /** `visible: [{user: id}]` — shown only to the listed users. */
    @Immutable
    data class Users(val userIds: Set<String>) : ViewVisibility
}

/**
 * Sealed hierarchy of card types R1HA renders natively. Adding a new
 * type means: declare a data class here, parse it in [LovelaceParser],
 * and add a branch in [com.github.itskenny0.r1ha.feature.dashboards.cards.LovelaceCardRenderer].
 *
 * Every variant carries [raw] so the editor's JSON view can show + edit
 * the original config without round-tripping through our typed model
 * (which would silently drop fields we don't understand yet).
 */
@Immutable
sealed class LovelaceCard {
    /** Card type string from the original config (`"entities"`, `"tile"`, etc.). */
    abstract val type: String

    /** Raw JSON config as HA returned it; the editor + Unsupported renderer
     *  both rely on this being preserved verbatim. */
    abstract val raw: JsonObject

    /** Vertical list of entity rows (and optional special rows). */
    @Immutable
    data class Entities(
        override val raw: JsonObject,
        val title: String?,
        val showHeaderToggle: Boolean?,
        /**
         * Items in the card's `entities:` array. Each is either a regular
         * [EntityRow] or a [SpecialRow] (divider, section, button, etc.).
         * Use [rowItems] to iterate over both; [entities] is kept for
         * backward compatibility and returns only the entity rows.
         */
        val rowItems: List<EntitiesItem>,
        /** HA `header:` slot rendered above the card body. Null = no header. */
        val header: LovelaceHeaderFooter? = null,
        /** HA `footer:` slot rendered below the card body. Null = no footer. */
        val footer: LovelaceHeaderFooter? = null,
    ) : LovelaceCard() {
        override val type: String = "entities"
        /** Backward-compat view: only the entity rows. */
        val entities: List<EntityRow> get() = rowItems.filterIsInstance<EntitiesItem.Entity>().map { it.row }
    }

    /** Compact grid of entity glyphs + state readouts. */
    @Immutable
    data class Glance(
        override val raw: JsonObject,
        val title: String?,
        val entities: List<EntityRow>,
        val columns: Int?,
        val showName: Boolean,
        val showState: Boolean,
        val showIcon: Boolean,
    ) : LovelaceCard() {
        override val type: String = "glance"
    }

    /** Single tappable action button. Either a bare action (no entity) or
     *  wired to a specific entity for state-coloured display. */
    @Immutable
    data class Button(
        override val raw: JsonObject,
        val entityId: String?,
        val name: String?,
        val icon: String?,
        val showName: Boolean,
        val showIcon: Boolean,
        val showState: Boolean,
        val tapAction: LovelaceAction?,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
        /** HA `color`: a theme colour name or `#rrggbb` applied to the icon/name
         *  when set. Null = use the state-derived accent. */
        val color: String? = null,
        /** HA `state_color`: when true, an active entity tints the icon/name with
         *  the state accent. When false the button stays neutral regardless of
         *  state. HA defaults this true for the button card. */
        val stateColor: Boolean = true,
    ) : LovelaceCard() {
        override val type: String = "button"
    }

    /**
     * Shortcut card (HA 2026.5): a tile-shaped one-tap launcher. Carries no
     * entity; the whole card fires [tapAction] (navigate / url / call-service /
     * assist). [label] / [description] / [icon] / [color] are optional overrides;
     * when null HA resolves them from the action (we best-effort the name from a
     * navigate path at render time and otherwise show a generic label).
     */
    @Immutable
    data class Shortcut(
        override val raw: JsonObject,
        /** HA 2026.5 `name:` key (legacy) and `label:` key - the primary line under the icon. */
        val name: String?,
        /** HA 2026.5 `label:` key - takes precedence over `name:` when both are set. */
        val label: String?,
        val icon: String?,
        val color: String?,
        val tapAction: LovelaceAction?,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
        /** HA 2026.5 `description:` secondary line below the label. */
        val description: String? = null,
        /** HA 2026.5 `vertical:` stacks the icon above the label. */
        val vertical: Boolean = false,
    ) : LovelaceCard() {
        override val type: String = "shortcut"
        /** Resolved display label: `label` wins over `name` to match HA's render order. */
        val displayLabel: String? get() = label?.takeUnless { it.isBlank() } ?: name?.takeUnless { it.isBlank() }
    }

    /**
     * Calendar card: a compact agenda list of events from one or more calendar
     * entities. The R1-appropriate default view is an agenda (date-grouped event
     * list) regardless of [initialView]. A `dayGridMonth` initial_view renders a
     * compact scrolling agenda - a full month grid is not practical at 640x480.
     *
     * Events are fetched via the same [HaRepository.fetchCalendarEvents] path the
     * native Calendars feature uses; [entityIds] drives which calendars are pulled.
     * Colors are per-entity, derived from a stable hash (same as the native agenda).
     */
    @Immutable
    data class Calendar(
        override val raw: JsonObject,
        val title: String?,
        /** Ordered list of calendar entity ids. */
        val entityIds: List<String>,
        /**
         * HA `initial_view`: "dayGridMonth" / "dayGridDay" / "listWeek" etc.
         * R1HA renders a compact agenda list regardless of this value; it is stored
         * for round-trip fidelity and future use.
         */
        val initialView: String?,
    ) : LovelaceCard() {
        override val type: String = "calendar"
    }

    /**
     * Home-summary card (HA 2026.x): a tile-shaped summary of one of seven
     * categories: light, climate, security, media_players, maintenance, energy,
     * persons. On R1HA the card taps to the nearest native screen for the category;
     * entity counts are derived from live state where available.
     */
    @Immutable
    data class HomeSummary(
        override val raw: JsonObject,
        /**
         * HA `summary:` - one of: light, climate, security, media_players,
         * maintenance, energy, persons. Unknown values render as a generic tile.
         */
        val summary: String,
        val vertical: Boolean = false,
        val tapAction: LovelaceAction? = null,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
    ) : LovelaceCard() {
        override val type: String = "home-summary"
    }

    /**
     * Updates card (HA informational): shows pending software updates and links
     * to the native Updates screen. [hideEmpty] when true hides the card if there
     * are no pending updates (not evaluated client-side; stored for HA parity).
     */
    @Immutable
    data class Updates(
        override val raw: JsonObject,
        val hideEmpty: Boolean = false,
        val vertical: Boolean = false,
        val tapAction: LovelaceAction? = null,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
    ) : LovelaceCard() {
        override val type: String = "updates"
    }

    /**
     * Repairs card (HA informational): shows open repair issues and links to the
     * native Repairs screen. [hideEmpty] when true hides the card if there are no
     * open issues.
     */
    @Immutable
    data class Repairs(
        override val raw: JsonObject,
        val hideEmpty: Boolean = false,
        val vertical: Boolean = false,
        val tapAction: LovelaceAction? = null,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
    ) : LovelaceCard() {
        override val type: String = "repairs"
    }

    /**
     * Empty-state card (HA): a friendly "no devices yet" card rendered when a
     * new HA instance has no devices. R1HA renders its [title] + [content] message
     * with the optional [icon]. Buttons are rendered as navigate tiles (each fires
     * its [tap_action]).
     */
    @Immutable
    data class EmptyState(
        override val raw: JsonObject,
        val title: String?,
        val content: String?,
        val icon: String?,
        /** HA `content_only`: when true, omit the card chrome and show only the
         *  message body. */
        val contentOnly: Boolean = false,
    ) : LovelaceCard() {
        override val type: String = "empty-state"
    }

    /** Modern compact tile (HA's current first-class card type). */
    @Immutable
    data class Tile(
        override val raw: JsonObject,
        val entityId: String,
        val name: String?,
        val icon: String?,
        val hideState: Boolean,
        val vertical: Boolean,
        val color: String?,
        val tapAction: LovelaceAction?,
        val holdAction: LovelaceAction? = null,
        val doubleTapAction: LovelaceAction? = null,
        /**
         * HA's separate ICON gesture slots. The tile splits its body and icon
         * into two action surfaces: tapping the body more-infos by default,
         * tapping the icon toggles/presses (for a toggleable domain) or does
         * nothing. A null [iconTapAction] falls back to
         * `getEntityDefaultTileIconAction(entity)`. Hold / double-tap stay null
         * when unconfigured (no icon gesture attached for them).
         */
        val iconTapAction: LovelaceAction? = null,
        val iconHoldAction: LovelaceAction? = null,
        val iconDoubleTapAction: LovelaceAction? = null,
        /**
         * HA `show_entity_picture`: when true and the entity reports an
         * `entity_picture`, the icon disc is replaced by that image (album art,
         * person avatar, camera thumbnail).
         */
        val showEntityPicture: Boolean = false,
        /**
         * HA `features_position`: "bottom" (default, features render below the
         * body) or "inline" (features render beside the body). On the 640px R1
         * screen "inline" renders the features as a compact trailing column.
         */
        val featuresPosition: String? = null,
        // HA's `features:` array. Each entry renders as a control row below the
        // tile body (cover open/close, light brightness, fan speed, climate HVAC
        // modes, alarm modes, lock commands, toggle, target temperature, select
        // options). A feature type R1HA doesn't model parses to
        // LovelaceTileFeature.Unsupported and is skipped at render time.
        val features: List<LovelaceTileFeature> = emptyList(),
        /**
         * HA 2023.11: ordered list of tokens that build the state line. Each
         * token is one of the reserved strings "state", "last_changed",
         * "last_updated" or an attribute key. Empty = use the default
         * [compactStateText] path.
         */
        val stateContent: List<String> = emptyList(),
        /**
         * HA 2025.11: controls which name the tile displays. One of:
         *  - null / "entity" (default): the entity's friendly_name
         *  - "device": the owning device's display name
         *  - "area": the entity's area name
         *  - "floor": the floor the entity's area belongs to
         * Space or comma-separated combos (e.g. "device area") resolve each
         * part and join the results with a space.
         */
        val nameType: String? = null,
    ) : LovelaceCard() {
        override val type: String = "tile"
    }

    /** Dedicated light card. Brightness + on/off; for full colour control
     *  the card-stack archetype is still the right surface. */
    @Immutable
    data class Light(
        override val raw: JsonObject,
        val entityId: String,
        val name: String?,
        val icon: String?,
        /**
         * HA's `tap_action` / `hold_action` / `double_tap_action`. HA's light
         * card defaults the icon tap to `toggle` and the hold to `more-info`
         * (hui-light-card.ts getStubConfig); a null here means "use that
         * default", resolved centrally in [ActionDispatcher].
         */
